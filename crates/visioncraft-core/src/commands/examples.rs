//! Example projects built from commands (`examples/*.json`, each a list of [command, params]):
//! `project.load_example` replaces the project with one, as one undo step.

use super::fail;
use crate::project::Project;
use crate::session::{CommandError, Session, parse};
use crate::spec::{ParamType as T, param, spec};
use serde::Deserialize;
use serde_json::{Value, json};

/// (name, commands) of every example.
pub const EXAMPLES: [(&str, &str); 3] = [
    ("garden", include_str!("../examples/garden.json")),
    ("estate", include_str!("../examples/estate.json")),
    ("beach-house", include_str!("../examples/beach-house.json")),
];

/// The files examples refer to, by their source (`example:<file>`): the estate's villa, a
/// sample of 3DCraft (MIT, Johan Coppens), and the beach house, made for this project and
/// generated by `examples/models/beach-house/generate.py` (see ATTRIBUTION.md).
const EXAMPLE_FILES: [(&str, &[u8]); 2] = [
    (
        "example:villa.3dcraft",
        include_bytes!("../examples/villa.3dcraft"),
    ),
    (
        "example:beach-house.3dcraft",
        include_bytes!("../examples/beach-house.3dcraft"),
    ),
];

/// The bytes of a model an example refers to (`source` of the form `example:<file>`).
pub fn example_file(source: &str) -> Option<&'static [u8]> {
    EXAMPLE_FILES
        .iter()
        .find(|(s, _)| *s == source)
        .map(|(_, b)| *b)
}

pub(super) fn register(s: &mut Session) {
    s.register_with_spec(
        spec(
            "project.load_example",
            "Open Example",
            "Replaces the project with an example built from commands: `garden`, a 20 by 30 m plot with a house block, terrace, lawn, border, path, carved pond, hornbeam hedge, three trees, path lights, a bollard and six viewpoints; `estate`, a 100 by 60 m plot round an imported 3DCraft villa with two large lawns, a brushed woodland, a border, a pond in the terrain, path lights, a planting on a hidden layer and three viewpoints; `beach-house`, a furnished single-storey beach house imported from 3DCraft (walls, glass, doors, kitchen, bathrooms, deck, carport) on sand, with library materials per element, catalogue furniture, interior downlights and ten viewpoints inside and out, one at dusk.",
            vec![param("name", T::String, "The example: garden, estate or beach-house.").required()],
            "{name, steps}",
            json!({"name": "garden"}),
        ),
        load_example,
    );
}

/// The project an example builds.
pub fn example(name: &str) -> Result<Project, String> {
    let (_, commands) = EXAMPLES
        .iter()
        .find(|e| e.0 == name)
        .ok_or_else(|| format!("no example `{name}`; there are: garden, estate, beach-house"))?;
    let steps: Vec<(String, Value)> =
        serde_json::from_str(commands).map_err(|e| format!("example {name}: {e}"))?;
    let mut s = Session::new(Project::default());
    for (command, params) in steps {
        s.run(&command, params)
            .map_err(|e| format!("example {name}, {command}: {e}"))?;
    }
    Ok(s.project().clone())
}

fn load_example(project: &mut Project, params: &Value) -> Result<Value, CommandError> {
    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct P {
        name: String,
    }
    let p: P = parse(params)?;
    *project = example(&p.name).map_err(fail)?;
    Ok(
        json!({"name": p.name, "shapes": project.shapes.len(), "plantings": project.generators.len()}),
    )
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_garden_builds_small_and_complete() {
        let (_, json) = super::EXAMPLES[0];
        assert!(json.len() < 50_000);
        let p = super::example("garden").unwrap();
        let names: Vec<&str> = p.shapes.iter().map(|s| s.name()).collect();
        for n in ["House", "Terrace", "Lawn", "Border", "Pond"] {
            assert!(names.contains(&n), "{names:?}");
        }
        assert_eq!(p.generators.len(), 7);
        assert_eq!(p.viewpoints.len(), 6);
        assert!(p.terrain.is_some());
        assert!(super::example("park").is_err());
    }

    #[test]
    fn the_estate_builds_large_and_messy() {
        let p = super::example("estate").unwrap();
        assert_eq!(p.models.len(), 1);
        assert!(super::example_file(&p.models[0].source).is_some_and(|b| b.len() > 10_000));
        let lawns: Vec<f32> = p
            .shapes
            .iter()
            .filter_map(|s| match s {
                crate::Shape::Area(a) if a.name.contains("lawn") => {
                    Some(crate::shape::shoelace_f32(&a.outline).abs() as f32)
                }
                _ => None,
            })
            .collect();
        assert!(
            lawns.len() == 2 && lawns.iter().all(|a| *a > 1000.0),
            "{lawns:?}"
        );
        assert!(p.layers.iter().any(|l| !l.visible));
        assert_eq!(p.viewpoints.len(), 3);
        assert!(p.viewpoints.iter().all(|v| v.time.is_none()));
        assert!(p.terrain.is_some() && p.generators.len() >= 7);
    }

    /// The villa stands on the ground as placed (no lift by hand): its terrace slab and its own
    /// lawn lie on the ground, so the rule in `shape::ground_faces` applies (the model drawn an
    /// area's lift up, draped areas cut out under those faces) instead of the two fighting.
    #[test]
    fn the_villa_lies_on_the_ground_by_the_rule() {
        let p = super::example("estate").unwrap();
        let m = &p.models[0];
        assert_eq!(m.transform.translation[1], 0.0, "no lift by hand");
        let model = crate::import_3dcraft(super::example_file(&m.source).unwrap()).unwrap();
        let t = p.terrain.as_deref().unwrap();
        let [tx, ty, tz] = m.transform.translation;
        let (sn, cs) = m.transform.rotation_y_deg.to_radians().sin_cos();
        let k = m.transform.scale;
        let place = |q: [f32; 3]| {
            let [x, y, z] = q.map(|c| c * k);
            [tx + cs * x + sn * z, ty + y, tz - sn * x + cs * z]
        };
        let faces = crate::ground_faces(&model, &place, &|x, z| t.height_at(x, z));
        let area: f32 = faces
            .iter()
            .map(|[a, b, c]| {
                ((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])).abs() / 2.0
            })
            .sum();
        assert!(area > 20.0, "{} ground triangles, {area} m2", faces.len());
    }

    /// Every example's pond is a level water surface over its carved bed, not a sheet draped
    /// under it (the estate's pond was a dry pit).
    #[test]
    fn every_example_pond_holds_water() {
        for (name, _) in super::EXAMPLES.iter().filter(|e| e.0 != "beach-house") {
            let p = super::example(name).unwrap();
            let t = p.terrain.as_deref().unwrap();
            let pond = p
                .shapes
                .iter()
                .find_map(|s| match s {
                    crate::Shape::Area(a) if a.name == "Pond" => Some(a),
                    _ => None,
                })
                .unwrap_or_else(|| panic!("{name}: no pond"));
            assert!(!pond.drape, "{name}: the water is draped");
            let n = pond.outline.len() as f32;
            let c = pond
                .outline
                .iter()
                .fold([0.0, 0.0], |a, q| [a[0] + q[0] / n, a[1] + q[1] / n]);
            let bed = t.height_at(c[0], c[1]).unwrap();
            assert!(
                pond.elevation > bed + 0.2 && pond.elevation < 0.0,
                "{name}: bed {bed}, water {}",
                pond.elevation
            );
        }
    }

    /// The beach house: one imported model with a material on every body, furniture, lights in
    /// every room and the terrace, and its views (dusk the only one with its own time).
    #[test]
    fn the_beach_house_builds_furnished_and_lit() {
        let p = super::example("beach-house").unwrap();
        assert_eq!(p.models.len(), 1);
        let file = super::example_file(&p.models[0].source).unwrap();
        assert!(
            file.len() > 100_000 && file.len() < 400_000,
            "{}",
            file.len()
        );
        assert_eq!(p.assignments.len(), 46);
        assert_eq!(p.generators.len(), 45);
        assert_eq!(p.lights.len(), 23);
        assert_eq!(p.viewpoints.len(), 10);
        assert_eq!(p.viewpoints.iter().filter(|v| v.time.is_some()).count(), 1);
        assert!(p.terrain.is_some());
    }

    #[test]
    fn the_pond_is_square_and_its_coping_stands_on_the_lawn() {
        let p = super::example("garden").unwrap();
        let t = p.terrain.as_deref().unwrap();
        let pond = p.shapes.iter().find(|s| s.name() == "Pond").unwrap();
        let crate::Shape::Area(a) = pond else {
            panic!()
        };
        assert_eq!(a.outline.len(), 4, "the outline as drawn");
        let edge = p.shapes.iter().find(|s| s.name() == "Pond edge").unwrap();
        let crate::Shape::Extrusion(e) = edge else {
            panic!()
        };
        let lift = crate::footing(&e.outline, &|x, z| t.height_at(x, z));
        let top = lift + e.base + e.height;
        assert!((top - 0.12).abs() < 0.02, "coping top {top} (lift {lift})");
    }
}
