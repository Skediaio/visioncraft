/// The furnished beach house (model, materials per body, furniture, lights), shared by the
/// `beach-house` example (on sand) and the `coast` example (on the mainland beach).
const BEACH_HOUSE: &str = include_str!("../examples/beach-house-furnished.json");

/// (name, command files run in order) of every example.
pub const EXAMPLES: [(&str, &[&str]); 4] = [
    ("garden", &[include_str!("../examples/garden.json")]),
    ("estate", &[include_str!("../examples/estate.json")]),
    (
        "beach-house",
        &[BEACH_HOUSE, include_str!("../examples/beach-house.json")],
    ),
    (
        "coast",
        &[BEACH_HOUSE, include_str!("../examples/coast.json")],
    ),
];

/// The files examples refer to, by their source (`example:<file>`): the estate's villa, a
/// sample of 3DCraft (MIT, Johan Coppens), and the beach house, made for this project and
/// generated by `examples/models/beach-house/generate.py` (see ATTRIBUTION.md).
const EXAMPLE_FILES: [(&str, &[u8]); 2] = [
    (
        "example:villa.3dcraft",
        include_bytes!("../examples/villa.3dcraft"),
    ),
    (
        "example:beach-house.3dcraft",
        include_bytes!("../examples/beach-house.3dcraft"),
    ),
];

/// The bytes of a model an example refers to (`source` of the form `example:<file>`).
pub fn example_file(source: &str) -> Option<&'static [u8]> {
    // Files saved before example sources were kept as names hold `<folder>/example:<file>`.
    let name = source.rsplit(['/', '\\']).next().unwrap_or(source);
    EXAMPLE_FILES
        .iter()
        .find(|(s, _)| *s == name)
        .map(|(_, b)| *b)
}

/// Whether `source` names a model carried inside the program (`example:<file>`), known to this
/// build or not.
pub fn is_example_source(source: &str) -> bool {
    source
        .rsplit(['/', '\\'])
        .next()
        .is_some_and(|n| n.starts_with("example:"))
}

pub(super) fn register(s: &mut Session) {
    s.register_with_spec(
        spec(
            "project.load_example",
            "Open Example",
            "Replaces the project with an example built from commands: `garden`, a 20 by 30 m plot with a house block, terrace, lawn, border, path, carved pond, hornbeam hedge, three trees, path lights, a bollard and six viewpoints; `estate`, a 100 by 60 m plot round an imported 3DCraft villa with two large lawns, a brushed woodland, a border, a pond in the terrain, path lights, a planting on a hidden layer and five viewpoints; `beach-house`, a furnished single-storey beach house imported from 3DCraft (walls, glass, doors, kitchen, bathrooms, deck, carport) on sand, with library materials per element, catalogue furniture, interior downlights and ten viewpoints inside and out, one at dusk; `coast`, the same furnished house on the mainland coast of southern California, 1.8 m above the sea with 20 m of beach from its deck to the waterline, its glass wall to the sea, the land rising inland to dunes of tussock grass and scrub with pines and olives in groups and a headland in the far west, and a coastal garden round it (a gravel drive between Italian cypresses, an entrance court on the front door's axis with bay standards and an olive, a garden room off the living side with a lawn, yew hedges and deep layered borders in drifts, a gravel garden of palms, pines, grasses and succulents, dune grass and ice plant towards the beach, pots on the deck, path lights) and fifteen viewpoints: the beach, the deck, the living room, a drone along the coast, golden hour, dusk, the water, the surf, the garden in summer, in winter and after 10 years.",
            vec![param("name", T::String, "The example: garden, estate, beach-house or coast.").required()],
            "{name, steps}",
            json!({"name": "garden"}),
        ),
        load_example,
    );
}

/// The project an example builds.
pub fn example(name: &str) -> Result<Project, String> {
    let (_, files) = EXAMPLES.iter().find(|e| e.0 == name).ok_or_else(|| {
        format!("no example `{name}`; there are: garden, estate, beach-house, coast")
    })?;
    let mut s = Session::new(Project::default());
    for commands in *files {
        let steps: Vec<(String, Value)> =
            serde_json::from_str(commands).map_err(|e| format!("example {name}: {e}"))?;
        for (command, params) in steps {
            s.run(&command, params)
                .map_err(|e| format!("example {name}, {command}: {e}"))?;
        }
    }
    Ok(s.project().clone())
}

fn load_example(project: &mut Project, params: &Value) -> Result<Value, CommandError> {
    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct P {
        name: String,
    }
    let p: P = parse(params)?;
    *project = example(&p.name).map_err(fail)?;
    Ok(
        json!({"name": p.name, "shapes": project.shapes.len(), "plantings": project.generators.len()}),
    )
}

