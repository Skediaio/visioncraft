    #[test]
    fn the_coast_is_a_mainland_beach_with_the_house_low_by_the_water() {
        let p = super::example("coast").unwrap();
        let sea = p.sea.clone().expect("a sea");
        let t = p.terrain.as_deref().unwrap();
        let h = |x, z| t.height_at(x, z).unwrap();
        // The house stands on its level plot 1.8 m above the sea.
        for (x, z) in [(-6.6, -10.5), (24.6, -12.3), (-0.6, 7.65), (24.6, 6.6)] {
            assert!(
                h(x, z).abs() < 0.05,
                "ground at the house at {x}, {z}: {}",
                h(x, z)
            );
        }
        assert!((sea.level + 1.8).abs() < 1e-4);
        // Sand from the deck steps down to the waterline 18 to 22 m beyond the deck (z 6.6), so the
        // sea fills the view from the house; the swash runs up to about 15 m from it.
        let dry = |z| h(8.0, z) > sea.level;
        assert!(dry(20.0) && h(8.0, 20.0) < sea.level + 1.2);
        let waterline = (40..=80).map(|z| z as f32 * 0.5).find(|z| !dry(*z));
        let waterline = waterline.expect("the waterline in front of the house");
        assert!(
            (24.6..=28.6).contains(&waterline),
            "waterline at z {waterline}"
        );
        assert!(h(8.0, 200.0) < sea.level - 3.0, "the bed deepens offshore");
        // Mainland: the land rises inland to the endless ground, which stays land behind the
        // coast to the horizon; beyond its far headland in the west, open sea again.
        let ground = p.view.ground.unwrap();
        assert!(ground.height > sea.level + 4.0);
        assert!(
            (h(0.0, -318.0) - ground.height).abs() < 0.5,
            "{}",
            h(0.0, -318.0)
        );
        assert!(sea.coast.len() >= 2 && sea.validate().is_ok());
        assert!(!sea.covers(0.0, -2000.0) && sea.covers(0.0, 2000.0));
        assert!(!sea.covers(-2000.0, 1200.0) && sea.covers(-2000.0, 1500.0));
        // Dune grass grown on the terrain: a layer of a tall lawn material over the sand, dense
        // on the ridge behind the house and in patches over the back dunes, a little on the
        // upper beach, none on the wet sand by the water nor on the house's plot.
        assert_eq!(t.layers.len(), 2);
        let dune = p
            .materials
            .iter()
            .find(|m| m.id == t.layers[1].material)
            .expect("the dune grass material");
        assert_eq!(dune.name, "Dune grass");
        assert!(matches!(
            dune.kind,
            crate::SurfaceKind::Lawn3d(l) if l.blade_height_m > 0.4 && l.blade_color.is_some()
        ));
        let grass = |x: f32, z: f32| f32::from(t.weights_at(x, z).unwrap()[1]) / 255.0;
        // The share of 100 spots from (x0, z) to (x1, z) where the grass grows well.
        let grown = |x0: f32, x1: f32, z: f32| {
            (0..100)
                .filter(|k| grass(x0 + (x1 - x0) * *k as f32 / 99.0, z) > 0.35)
                .count()
        };
        let crest = grown(-300.0, -80.0, -77.0);
        assert!(crest > 60, "{crest} of 100 on the crest");
        let back = grown(-450.0, 450.0, -230.0);
        assert!((10..80).contains(&back), "{back} of 100 on the back dunes");
        let beach = grown(-100.0, 100.0, 15.0);
        assert!(
            (3..50).contains(&beach),
            "{beach} of 100 on the upper beach"
        );
        for (x0, x1, z) in [(-100.0, 100.0, 22.0), (-30.0, 40.0, -20.0)] {
            assert_eq!(grown(x0, x1, z), 0, "grass at z {z}");
        }
        // The beach house itself, with its furniture and lights.
        assert_eq!(p.models.len(), 1);
        assert_eq!(p.models[0].source, "example:beach-house.3dcraft");
        assert_eq!(p.models[0].transform.translation, [0.0, 0.0, 0.0]);
        assert_eq!(p.lights.len(), 37); // the furnished house's; the garden's path lights are planting lamps
        let names: Vec<&str> = p.shapes.iter().map(|s| s.name()).collect();
        assert_eq!(
            names,
            [
                "Drive",
                "Entrance court",
                "Garden room lawn",
                "Garden path",
                "Beach walk",
                "East gravel garden",
                "Garden room north bed",
                "Garden room west bed",
                "Garden room south bed",
                "Court west bed",
                "Court east bed",
                "Court olive bed"
            ]
        );
        assert_eq!(p.assignments.len(), 46 + names.len());
        assert_eq!(p.viewpoints.len(), 15);
        // Golden hour, dusk and winter carry their own date and hour.
        assert_eq!(p.viewpoints.iter().filter(|v| v.time.is_some()).count(), 3);
        assert!(p.viewpoints.iter().any(|v| v.years.is_some()));
        // A finished garden: tens of trees and large shrubs, hundreds of perennials and grasses,
        // nothing on the sea bed, nothing but low dune planting in front of the glass wall.
        let house = super::example("beach-house").unwrap().generators.len();
        let mut trees = 0;
        let mut small = 0;
        for g in &p.generators[house..] {
            let mut e = crate::evaluate(g, &|x, z| t.height_at(x, z));
            let n = e.placements.len();
            crate::keep_dry(Some(&sea), &mut e, &|_| false);
            assert_eq!(e.placements.len(), n, "{} reaches into the water", g.name());
            if g.name().starts_with("Inland") || g.name().starts_with("Coastal scrub") {
                continue;
            }
            for pl in &e.placements {
                let [x, _, z] = pl.position;
                let open = (-0.5..21.5).contains(&x) && (6.7..40.0).contains(&z);
                assert!(
                    !open || ["Dune", "Ice"].iter().any(|w| g.name().starts_with(w)),
                    "{} at {x}, {z} stands in the view from the glass wall",
                    g.name()
                );
                let tree = [
                    "cupressus",
                    "olea",
                    "phoenix",
                    "trachycarpus",
                    "pinus",
                    "ficus",
                    "laurus",
                    "rosa-shrub",
                    "hibiscus",
                    "photinia-red",
                    "cortaderia",
                ]
                .iter()
                .any(|w| pl.asset.contains(w));
                if tree {
                    trees += 1;
                } else if !pl.asset.contains("hedge") && !pl.asset.contains("light") {
                    small += 1;
                }
            }
        }
        assert!((25..=60).contains(&trees), "{trees} trees and large shrubs");
        assert!(small > 300, "{small} perennials and grasses");
    }

    /// Four ready-made films of 10 to 20 s whose cameras stay above the ground and the sea, and
    /// whose walks keep clear of walls, hedges and trunks.
    #[test]
    fn the_coast_comes_with_four_films_that_stay_clear_of_the_ground_and_the_walls() {
        use crate::film::{Env, Timeline, terrain_ground};
        let p = super::example("coast").unwrap();
        let sea = p.sea.clone().expect("a sea");
        let names: Vec<&str> = p.films.iter().map(|f| f.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "Arrival",
                "Drone over the coast",
                "Garden walk",
                "Golden hour by the sea"
            ]
        );
        let ground = |x: f32, z: f32| terrain_ground(&p, x, z);
        let env = Env::new(&p, &ground);
        let obstacles =
            crate::route::Obstacles::from_scene(&crate::reference::Scene::new(&p, None));
        for film in &p.films {
            assert!([24, 25].contains(&film.fps), "{}", film.name);
            let tl = Timeline::new(film, &env).unwrap();
            let len = film.duration(&env).unwrap();
            assert!((10.0..=20.0).contains(&len), "{}: {len} s", film.name);
            let walk = film.name != "Drone over the coast";
            let steps = (len * 4.0) as usize;
            for i in 0..=steps {
                let f = tl.camera_at((i as f32 / 4.0).min(len)).unwrap();
                let [x, y, z] = f.eye;
                let floor = ground(x, z).max(if sea.covers(x, z) {
                    sea.level
                } else {
                    f32::MIN
                });
                let want = if walk { 1.5 } else { 3.0 };
                assert!(
                    y >= floor + want,
                    "{}: eye {:?} at {:.2} s is {:.2} m above the ground or sea",
                    film.name,
                    f.eye,
                    i as f32 / 4.0,
                    y - floor
                );
                if walk && let Some((what, d)) = obstacles.nearest([x, z]) {
                    assert!(
                        d >= 0.3,
                        "{}: eye {:?} is {d:.2} m from {what}",
                        film.name,
                        f.eye
                    );
                }
            }
        }
    }

    #[test]
    fn the_pond_is_square_and_its_coping_stands_on_the_lawn() {
        let p = super::example("garden").unwrap();
        let t = p.terrain.as_deref().unwrap();
        let pond = p.shapes.iter().find(|s| s.name() == "Pond").unwrap();
        let crate::Shape::Area(a) = pond else {
            panic!()
        };
        assert_eq!(a.points.len(), 4, "the outline as drawn");
        let edge = p.shapes.iter().find(|s| s.name() == "Pond edge").unwrap();
        let crate::Shape::Extrusion(e) = edge else {
            panic!()
        };
        let lift = crate::footing(&e.points, &|x, z| t.height_at(x, z));
        let top = lift + e.base + e.height;
        assert!((top - 0.12).abs() < 0.02, "coping top {top} (lift {lift})");
    }
