//! Second part of the library: more trees, conifers, a feather palm, shrubs, clipped forms,
//! grasses, perennials and bulbs, ground covers, wall climbers, kitchen-garden and pond plants.
//! As in the first part, every value is chosen here from each plant's habit.

use super::*;
use crate::{ClipShape, ClippedParams, ConiferParams, GroundCoverParams};

fn ros(
    leaves: u16,
    leaf_m: f32,
    e0: f32,
    e1: f32,
    arch: f32,
    shoots: bool,
    stalks: u16,
    spread: f32,
    fh: f32,
) -> Form {
    Form::Rosette(RosetteParams {
        leaves,
        leaf_m,
        min_elev_deg: e0,
        max_elev_deg: e1,
        arch_deg: arch,
        shoots,
        stalks,
        stalk_spread_deg: spread,
        foliage_height: fh,
    })
}

fn grass(
    blades: u16,
    fans: u16,
    bw: f32,
    base: f32,
    a0: f32,
    a1: f32,
    droop: f32,
    fh: f32,
    plumes: u16,
    plume_m: f32,
    spread: f32,
) -> Form {
    Form::Tussock(TussockParams {
        blades,
        fans,
        blade_width_m: bw,
        base_radius_m: base,
        min_angle_deg: a0,
        max_angle_deg: a1,
        droop,
        foliage_height: fh,
        plumes,
        plume_m,
        plume_spread_deg: spread,
    })
}

fn clip(shape: ClipShape, roughness: f32, tuft_m: f32, stem_m: f32) -> Form {
    Form::Clipped(ClippedParams {
        shape,
        roughness,
        tuft_m,
        stem_m,
    })
}

fn gc(cards: u16, depth_m: f32, tilt_deg: f32) -> Form {
    Form::GroundCover(GroundCoverParams {
        cards,
        depth_m,
        tilt_deg,
    })
}

fn climb(patch_width_m: f32, stems: u16, depth_m: f32) -> Form {
    Form::Climber(ClimberParams {
        patch_width_m,
        stems,
        depth_m,
    })
}

fn shrub(
    stems: u16,
    spread: f32,
    base: f32,
    ratio: f32,
    leader: f32,
    cb: f32,
    shape: CrownShape,
    l: [LevelParams; 3],
    leaf_level: u8,
    leaf_start: f32,
) -> Form {
    Habit::multi(stems, spread, base, ratio, leader, cb, shape, l)
        .leaves_on(leaf_level, leaf_start)
        .form()
}

/// Three usual levels for a broadleaf tree: limbs, branches (opposite if `opp`), twigs.
fn levels(
    limbs: u16,
    limb_len: f32,
    limb_down: f32,
    curve: f32,
    var: f32,
    opp: bool,
) -> [LevelParams; 3] {
    let (rot, wh) = if opp { (90.0, 2) } else { (137.5, 1) };
    [
        lv(
            limbs, limb_len, limb_down, 137.5, 1, curve, var, 0.0, 6, 0.6, 0.25,
        ),
        lv(8, 0.5, 45.0, rot, wh, -5.0, var * 0.8, -0.1, 4, 0.5, 0.2),
        lv(6, 0.45, 40.0, rot, wh, 0.0, var, 0.0, 2, 0.5, 0.25),
    ]
}

